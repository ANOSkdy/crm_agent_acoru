import { config } from 'dotenv'
import { neon } from '@neondatabase/serverless'
import { randomUUID, randomBytes, createHash } from 'node:crypto'
import { mkdirSync, writeFileSync, readFileSync, unlinkSync, existsSync } from 'node:fs'

config({ path: '.env.local', quiet: true })
async function main() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL missing')
  const sql = neon(process.env.DATABASE_URL)
  if (process.argv[2] === 'renew') {
    const fixture = JSON.parse(readFileSync('.local-test/fixture.json', 'utf8'))
    await sql`UPDATE user_sessions SET expires_at=now()+interval '2 hours' WHERE token_hash IN (${createHash('sha256').update(fixture.token).digest('hex')},${createHash('sha256').update(fixture.viewerToken).digest('hex')}) AND user_id IN (${fixture.userId},${fixture.viewerId})`
    console.log('Renewed temporary API test sessions')
    return
  }
  if (process.argv[2] === 'cleanup') {
    const fixture = JSON.parse(readFileSync('.local-test/fixture.json', 'utf8'))
    // Remove only the records generated by this script, identified by random IDs.
    await sql.transaction([
      sql`DELETE FROM agent_change_requests WHERE run_id IN (SELECT r.id FROM agent_runs r JOIN agent_threads t ON t.id=r.thread_id WHERE t.created_by IN (${fixture.userId},${fixture.viewerId}))`,
      sql`DELETE FROM agent_messages WHERE thread_id IN (SELECT id FROM agent_threads WHERE created_by IN (${fixture.userId},${fixture.viewerId}))`,
      sql`DELETE FROM agent_runs WHERE thread_id IN (SELECT id FROM agent_threads WHERE created_by IN (${fixture.userId},${fixture.viewerId}))`,
      sql`DELETE FROM agent_threads WHERE created_by IN (${fixture.userId},${fixture.viewerId})`,
      sql`DELETE FROM agent_change_requests WHERE deal_id = ${fixture.dealId}`,
      sql`DELETE FROM agent_messages WHERE thread_id IN (SELECT id FROM agent_threads WHERE deal_id = ${fixture.dealId})`,
      sql`DELETE FROM agent_runs WHERE thread_id IN (SELECT id FROM agent_threads WHERE deal_id = ${fixture.dealId})`,
      sql`DELETE FROM agent_threads WHERE deal_id = ${fixture.dealId}`,
      sql`DELETE FROM deal_decisions WHERE deal_id = ${fixture.dealId}`,
      sql`DELETE FROM deal_contexts WHERE deal_id = ${fixture.dealId}`,
      sql`DELETE FROM tasks WHERE deal_id = ${fixture.dealId}`,
      sql`DELETE FROM activities WHERE deal_id = ${fixture.dealId}`,
      sql`DELETE FROM ai_summaries WHERE company_id = ${fixture.companyId} OR deal_id = ${fixture.dealId}`,
      sql`DELETE FROM audit_logs WHERE user_id = ${fixture.userId} OR user_id = ${fixture.viewerId} OR target_id = ${fixture.dealId}`,
      sql`DELETE FROM deals WHERE id = ${fixture.dealId} AND company_id = ${fixture.companyId}`,
      sql`DELETE FROM companies WHERE id = ${fixture.companyId}`,
      sql`DELETE FROM tasks WHERE deal_id=${fixture.otherDealId??fixture.dealId}`,
      sql`DELETE FROM deals WHERE id=${fixture.otherDealId??fixture.dealId}`,
      sql`DELETE FROM companies WHERE id=${fixture.otherCompanyId??fixture.companyId}`,
      sql`DELETE FROM user_sessions WHERE user_id IN (${fixture.userId}, ${fixture.viewerId})`,
      sql`DELETE FROM users WHERE id IN (${fixture.userId}, ${fixture.viewerId}) AND email LIKE '%@agent-test.invalid'`,
    ])
    unlinkSync('.local-test/fixture.json')
    console.log('Removed test records and sessions')
    return
  }
  if (existsSync('.local-test/fixture.json')) throw new Error('Clean up the existing test fixture before creating another')
  const fixture = {
    userId: randomUUID(), viewerId: randomUUID(), companyId: randomUUID(), dealId: randomUUID(),
    login: `agent-test-${randomBytes(5).toString('hex')}`, password: randomBytes(24).toString('base64url'),
    token: randomBytes(32).toString('base64url'), viewerToken: randomBytes(32).toString('base64url'),
    ...(process.argv[2]==='workspace'?{otherCompanyId:randomUUID(),otherDealId:randomUUID()}:{}),
  }
  mkdirSync('.local-test', { recursive: true })
  // Write the cleanup identifiers before mutation, so failed setup remains recoverable.
  writeFileSync('.local-test/fixture.json', JSON.stringify(fixture))
  await sql.transaction([
    sql`INSERT INTO users(id,name,email,login_id,password_hash,role) VALUES (${fixture.userId}, '検証担当', ${fixture.login + '@agent-test.invalid'}, ${fixture.login}, crypt(${fixture.password}, gen_salt('bf')), 'admin')`,
    sql`INSERT INTO users(id,name,email,login_id,password_hash,role) VALUES (${fixture.viewerId}, '検証閲覧者', ${fixture.login + '-viewer@agent-test.invalid'}, ${fixture.login + '-viewer'}, crypt(${fixture.password}, gen_salt('bf')), 'viewer')`,
    sql`INSERT INTO companies(id,name) VALUES (${fixture.companyId}, '検証用サンプル会社')`,
    sql`INSERT INTO deals(id,company_id,title,amount,probability,owner_user_id) VALUES (${fixture.dealId}, ${fixture.companyId}, '案件アシスタント 動作検証', 500000, 40, ${fixture.userId})`,
    sql`INSERT INTO user_sessions(user_id,token_hash,expires_at) VALUES (${fixture.userId}, ${createHash('sha256').update(fixture.token).digest('hex')}, now() + interval '2 hours'), (${fixture.viewerId}, ${createHash('sha256').update(fixture.viewerToken).digest('hex')}, now() + interval '2 hours')`,
    ...(fixture.otherCompanyId&&fixture.otherDealId?[
      sql`INSERT INTO companies(id,name) VALUES(${fixture.otherCompanyId},'検証用比較会社')`,
      sql`INSERT INTO deals(id,company_id,title,amount,probability) VALUES(${fixture.otherDealId},${fixture.otherCompanyId},'比較用サポート案件',900000,80)`,
      sql`INSERT INTO tasks(company_id,deal_id,title,due_date,priority) VALUES(${fixture.companyId},${fixture.dealId},'検証用・期限超過の見積確認',(now() AT TIME ZONE 'Asia/Tokyo')::date-1,'high')`,
    ]:[]),
  ])
  console.log('Created temporary test fixture; credentials saved in ignored .local-test directory')
}
main().catch((error) => { console.error('Fixture operation failed', { code: error?.code ?? 'unknown', column: error?.column }); process.exitCode = 1 })
